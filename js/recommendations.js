// js/recommendations.js — Персональные программы тренировок и питания по ИМТ, весу, росту и интернет-рекомендации
import { round1 } from './utils.js';

export function buildActivityAndDietPlan(profile) {
  if (!profile) return null;

  const { bmi, age, currentWeight, height, isPediatric, targetKcal, macros, adaptationCount = 0 } = profile;
  const waterLiters = round1((currentWeight * 33) / 1000);

  let workoutPlan = {};
  let dietStrategy = {};

  if (isPediatric) {
    workoutPlan = {
      title: 'Детский и подростковый физкультурный режим (ВОЗ)',
      stepsGoal: '8 000 – 10 000 шагов или 60 мин активных игр',
      cardio: 'Плавание, велосипед, командные игры, быстрая ходьба 4–5 раз в неделю по 45–60 минут.',
      strength: 'Упражнения с собственным весом (гимнастика, ОФП, турник, планка) 2–3 раза в неделю без осевой нагрузки на позвоночник.',
      intensity: 'Умеренная и игровая (пульс 120–145 уд/мин).'
    };
    dietStrategy = {
      title: 'Сбалансированный рацион для растущего организма',
      mealsCount: '4–5 приёмов пищи (3 основных + 1–2 полезных перекуса)',
      principles: [
        'Полный отказ от сладких газировок, пакетированных соков и фастфуда в пользу цельных фруктов и ягод.',
        'Обязательный белок в каждый основной приём пищи (птица, рыба, творог, яйца) для сохранения мышечной и костной ткани.',
        'Сложные углеводы утром и в обед (гречка, овсянка, бурый рис, цельнозерновой хлеб).',
        `Водный баланс: около ${waterLiters} л чистой воды в сутки.`
      ]
    };
  } else if (bmi >= 35) {
    // Ожирение II и III степени — щадящая нагрузка на суставы
    workoutPlan = {
      title: 'Щадящий суставной протокол (LISS + ЛФК)',
      stepsGoal: `${7000 + adaptationCount * 1000} шагов в день в спокойном темпе`,
      cardio: 'Исключить бег и прыжки! Рекомендуется: плавание, аквааэробика, велотренажёр со спинкой или эллипс 4–5 раз в неделю по 35–45 минут.',
      strength: 'Круговые тренировки в тренажёрах сидя/лёжа и ЛФК для укрепления кора 2–3 раза в неделю.',
      intensity: 'Низкая, жиросжигающая зона пульса (110–125 уд/мин).'
    };
    dietStrategy = {
      title: 'Высокообъёмное питание с низкой калорийной плотностью (Volumetrics)',
      mealsCount: '3–4 чётких приёма пищи без хаотичных перекусов',
      principles: [
        'Правило тарелки: 50% объёма каждого приёма пищи должны составлять некрахмалистые овощи и зелень (огурцы, капуста, брокколи, томаты).',
        'Приоритет постного белка (треска, минтай, индейка, куриная грудка, яичные белки, творог до 2–5%).',
        'Минимизация жидких калорий, соусов, жарки на масле (использовать запекание, гриль, варку на пару).',
        `Норма воды: ${waterLiters} л в сутки (стакан воды за 20 минут до приёма пищи).`
      ]
    };
  } else if (bmi >= 25) {
    // Избыточная масса (Предожирение) и Ожирение I степени
    workoutPlan = {
      title: 'Комбинированный метаболический протокол (Силовые + Кардио)',
      stepsGoal: `${9000 + adaptationCount * 1500} шагов ежедневно`,
      cardio: 'Быстрая ходьба в горку (наклон дорожки 5–8%), эллипс или велосипед 3–4 раза в неделю по 40 минут.',
      strength: 'Полноценные силовые тренировки на всё тело (FullBody) 3 раза в неделю для удержания мышц и высокого метаболизма.',
      intensity: 'Средняя (пульс 125–140 уд/мин).'
    };
    dietStrategy = {
      title: 'Белково-сбалансированный рацион с контролем гликемической нагрузки',
      mealsCount: '3–4 приёма пищи с интервалом 3.5–4 часа',
      principles: [
        `Высокая квота белка (${macros.protein} г/день) для максимального термического эффекта пищи и сытости.`,
        'Перенос 70% дневной нормы углеводов на первую половину дня и приём пищи перед/после тренировки.',
        'Ужин за 3 часа до сна: нежирный белок + клетчатка (зелёные овощи) без быстрых углеводов.',
        `Водный режим: ${waterLiters} л чистой воды в сутки.`
      ]
    };
  } else {
    // Нормальный вес или рекомпозиция
    workoutPlan = {
      title: 'Протокол рекомпозиции тела и рельефа',
      stepsGoal: `${10000 + adaptationCount * 1000} шагов ежедневно`,
      cardio: '2–3 сессии умеренного кардио по 30 минут или 1–2 интервальные тренировки (HIIT) в неделю.',
      strength: 'Силовой прогрессивный тренинг 3–4 раза в неделю (акцент на базовые многосуставные движения).',
      intensity: 'Средне-высокая (пульс 130–155 уд/мин).'
    };
    dietStrategy = {
      title: 'Гибкий контроль макронутриентов (IIFYM / Рекомпозиция)',
      mealsCount: '3–4 приёма пищи под график тренировок',
      principles: [
        `Точное попадание в целевой коридор калорий (${targetKcal} ккал) и белка (${macros.protein} г).`,
        'Источники полезных жиров (авокадо, жирная морская рыба, орехи, оливковое масло) — не менее 25% рациона.',
        '85% рациона — цельные минимально обработанные продукты, 15% — допустимая гибкость в рамках калорийности.',
        `Водный баланс: ${waterLiters} л в сутки.`
      ]
    };
  }

  return { workoutPlan, dietStrategy, waterLiters };
}

/**
 * Запрашивает актуальные данные из открытых интернет-источников (Wikipedia REST API + OpenFoodFacts)
 * при срабатывании автоматической перестройки программы после 2 недель плато.
 */
export async function fetchInternetAdaptationAdvice(profile, reasonType) {
  const queryTopic = reasonType === 'weight_gain' ? 'Дефицит_калорий' : 'Метаболическая_адаптация';
  let wikiExcerpt = '';
  let suggestedFoods = [];

  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 3200);
    const res = await fetch('https://ru.wikipedia.org/api/rest_v1/page/summary/%D0%9E%D1%81%D0%BD%D0%BE%D0%B2%D0%BD%D0%BE%D0%B9_%D0%BE%D0%B1%D0%BC%D0%B5%D0%BD', {
      signal: controller.signal
    });
    clearTimeout(timer);
    if (res.ok) {
      const data = await res.json();
      if (data.extract) {
        wikiExcerpt = data.extract.slice(0, 220) + '...';
      }
    }
  } catch (_) {
    // Офлайн-резерв
  }

  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 3200);
    const offUrl = 'https://world.openfoodfacts.org/cgi/search.pl?search_terms=high+protein+low+fat&search_simple=1&action=process&json=1&page_size=4';
    const res = await fetch(offUrl, { signal: controller.signal });
    clearTimeout(timer);
    if (res.ok) {
      const data = await res.json();
      suggestedFoods = (data.products || [])
        .map(p => p.product_name_ru || p.product_name)
        .filter(Boolean)
        .slice(0, 3);
    }
  } catch (_) {
    // Офлайн-резерв
  }

  const protocolSteps = [
    'Увеличена норма бытовой активности (NEAT): +1 500 шагов к ежедневной цели для разгона расхода энергии.',
    'Белковая квота повышена до верхней безопасной границы для защиты мышц и повышения термического эффекта пищи (TEF).',
    'Внедрено правило «белково-овощного ужина»: перенос сложных углеводов на завтрак и обед.',
    suggestedFoods.length > 0
      ? `Рекомендованные продукты из онлайн-базы OpenFoodFacts: ${suggestedFoods.join(', ')}.`
      : 'Рекомендована ротация источников белка: белая рыба (треска/минтай), грудка индейки, обезжиренный творог и бобовые.'
  ];

  return {
    sourceLabel: wikiExcerpt ? 'Синхронизировано с онлайн-базой знаний (Wikipedia API + OpenFoodFacts)' : 'Локальный клинический протокол преодоления плато',
    wikiNote: wikiExcerpt || 'При длительном сохранении одного веса происходит адаптивный термогенез — снижение энергозатрат на движение и базовый обмен.',
    protocolSteps
  };
}
